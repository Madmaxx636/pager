// Writes THIRD_PARTY_LICENSES.md: the licence of every package Pager ships, read from each project's installed packages.
// Run after installing dependencies:  node scripts/licenses.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const projects = [["web app and desktop app", "app"], ["desktop shell", "desktop"], ["server API", "api"], ["GroupMe bridge", "bridges/groupme"]];
const out = ["# Third-party licences", "", "Pager itself is AGPL-3.0-only. It includes the packages below, each under its own licence. Generated by `scripts/licenses.mjs`.", ""];

for (const [title, dir] of projects) {
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const prod = new Set(Object.keys(pkg.dependencies ?? {}));
  const rows = new Map();
  const seen = new Set();
  const visit = (name, from) => {
    let p = join(from, "node_modules", name, "package.json");
    if (!existsSync(p)) p = join(dir, "node_modules", name, "package.json");
    if (!existsSync(p) || seen.has(p)) return;
    seen.add(p);
    const m = JSON.parse(readFileSync(p, "utf8"));
    const lic = typeof m.license === "string" ? m.license : m.license?.type ?? (m.licenses ?? []).map((l) => l.type).join(" OR ") ?? "unknown";
    rows.set(`${m.name}@${m.version}`, lic || "unknown");
    for (const d of Object.keys(m.dependencies ?? {})) visit(d, join(p, ".."));
  };
  for (const d of prod) visit(d, dir);
  out.push(`## ${title} (\`${dir}\`)`, "", "| Package | Licence |", "|---|---|");
  for (const [k, v] of [...rows].sort()) out.push(`| ${k} | ${v} |`);
  out.push("");
}
out.push("## Android app", "", "Main libraries (all Apache-2.0 unless noted): Jetpack Compose and AndroidX, Material 3 and its icons, Kotlin and kotlinx.serialization / coroutines, OkHttp,",
  "ZXing (QR codes), the matrix-rust-sdk crypto bindings (`org.matrix.rustcomponents:crypto-android`, Apache-2.0) and JNA (Apache-2.0 / LGPL-2.1 dual).", "",
  "## Bridges (separate programs run by the server)", "", "WhatsApp, Signal, Google Messages, Messenger, Slack, X, Bluesky and LinkedIn use the open-source mautrix bridges (AGPL-3.0), run as unmodified container images.",
  "Synapse (AGPL-3.0 and a commercial licence), PostgreSQL (PostgreSQL licence), Caddy (Apache-2.0).", "");
writeFileSync("THIRD_PARTY_LICENSES.md", out.join("\n"));
console.log("wrote THIRD_PARTY_LICENSES.md");
